"""Build local_game/street-ultimate-data.js from the matted ultimate assets.

Only keys that resolve to exactly one hero (and are not marked shared in the
existing FX table) are exposed as triggers, so a shared effect used by another
skill can never be swallowed by the overlay.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'local_game/assets/street/ultimate'
FX_PREVIEW = ROOT / 'local_game/fx-preview-data.js'
TARGET = ROOT / 'local_game/street-ultimate-data.js'


def ult_rows() -> list[dict]:
    text = FX_PREVIEW.read_text('utf8')
    rows = json.loads(text[text.find('['):text.rfind(']') + 1])
    return [r for r in rows if r.get('slot') == '大招']


def main() -> dict:
    rows = ult_rows()
    owners: dict[str, set[int]] = {}
    shared: set[str] = set()
    for row in rows:
        owners.setdefault(row['key'], set()).add(int(row['heroId']))
        if row.get('shared'):
            shared.add(row['key'])

    heroes = {}
    shared_only = []
    for meta_path in sorted(ASSETS.glob('*/meta.json')):
        meta = json.loads(meta_path.read_text('utf8'))
        hid = int(meta['heroId'])
        all_keys = list(meta['keys'])
        hero_keys = [k for k in all_keys if len(owners.get(k, ())) == 1 and k not in shared]
        if not hero_keys:
            shared_only.append(hid)
        heroes[str(hid)] = {
            'dir': meta_path.parent.relative_to(ROOT / 'local_game').as_posix(),
            'canvas': int(meta['canvas']),
            'frames': int(meta['frames']),
            'fps': int(meta['fps']),
            'name': meta['name'],
            'keys': hero_keys,
            'allKeys': all_keys,
            'files': meta['files'],
            'boxes': meta['boxes'],
        }

    lines = [
        '/* AUTO-GENERATED by tools/build_street_ultimate_data.py - do not edit. */',
        '/* Original container frame counts/fps are kept; frames are transparent WebP. */',
        'window.StreetUltimateData = {',
        '  generatedBy: "tools/build_street_ultimate_data.py",',
        '  heroes: ' + json.dumps(heroes, ensure_ascii=False, separators=(',', ':')),
        '};',
        '',
    ]
    TARGET.write_text('\n'.join(lines), 'utf8')
    keys = sum(len(h['keys']) for h in heroes.values())
    frames = sum(h['frames'] for h in heroes.values())
    return {'heroes': len(heroes), 'keys': keys, 'frames': frames,
            'bytes': TARGET.stat().st_size, 'sharedOnly': shared_only}


if __name__ == '__main__':
    print(json.dumps(main(), ensure_ascii=False))
