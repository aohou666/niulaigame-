import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const context={Promise,Date,Utils:{Socket:{send(){throw Error('Unexpected live server call');}}}};context.window=context;
vm.createContext(context);vm.runInContext(fs.readFileSync('local_game/offline-read-rpc.js','utf8'),context);
const api=context.OfflineReadRPC;api.installEarly();
const current=Date.now()/1000,clock=await context.Utils.Socket.send('worldEmpires','GetWorldEmpiresCurDt');
assert(clock.startDt<=current&&current<clock.endDt);
const pending=context.Utils.Socket.send('peakWar','GetPeakWarFreedomInfo');let invoked=false;
api.setTrainingRead((module,action)=>{invoked=true;assert.equal(module,'peakWar');assert.equal(action,'GetPeakWarFreedomInfo');return {info:{rank:8}};});
assert.equal((await pending).info.rank,8);assert(invoked);
let save={kits:[{uuid:'kit-1'}],mounts:[{uuid:'mount-1'}],mountEquips:[{uuid:'equip-1'}],guildDefence:{code:3,stageInfos:[{code:3,num:1,targeteds:[]}]}};
api.setSave(()=>save);
assert.equal((await api.read('kit','GetKitInfo')).kitList[0].uuid,'kit-1');
assert.equal((await api.read('mount','GetMountInfo')).mountList[0].uuid,'mount-1');
assert.equal((await api.read('mountEquip','GetMountEquipInfo')).equipList[0].uuid,'equip-1');
assert.equal((await api.read('guildDefence','GetGuildDefenceInfo')).playerInfo.code,3);
save={kits:[{uuid:'updated'}]};assert.equal((await api.read('kit','GetKitInfo')).kitList[0].uuid,'updated');
assert.equal(api.read('kit','UnknownMutation'),null);
console.log('OFFLINE_READ_RPC_OK: deferred reads, live save state, local clock and unsupported action boundary');
